fun matchesSearchQuery(option: String, query: String): Boolean {
    val trimmedQuery = query.trim()
    if (trimmedQuery.isEmpty()) return true
    if (option.isBlank()) return false

    if (option.contains(trimmedQuery, ignoreCase = true)) return true

    val asciiOption = com.example.data.model.UserProfile.normalizeDigitsToAscii(option)
    val asciiQuery = com.example.data.model.UserProfile.normalizeDigitsToAscii(trimmedQuery)
    if (asciiOption.contains(asciiQuery, ignoreCase = true)) return true

    val normQuery = normalizeBanglaSearchText(trimmedQuery)
    if (normalizeBanglaSearchText(option).contains(normQuery)) return true

    val banglaTranslated = translateValueToBangla(option)
    if (banglaTranslated.contains(trimmedQuery, ignoreCase = true)) return true
    if (normalizeBanglaSearchText(banglaTranslated).contains(normQuery)) return true

    val locationBn = com.example.data.model.BangladeshLocationData.getBanglaName(option)
    if (locationBn != null) {
        if (locationBn.contains(trimmedQuery, ignoreCase = true)) return true
        if (normalizeBanglaSearchText(locationBn).contains(normQuery)) return true
    }

    val lowerOption = option.trim().lowercase()
    val synonyms = extraBanglaSearchSynonyms[lowerOption]
    if (synonyms != null) {
        if (synonyms.any { syn ->
                syn.contains(trimmedQuery, ignoreCase = true) ||
                    normalizeBanglaSearchText(syn).contains(normQuery)
            }
        ) {
            return true
        }
    }

    // Check Bangla keyword to English hints
    for ((bnKey, enHints) in banglaKeywordToEnglishHints) {
        val normKey = normalizeBanglaSearchText(bnKey)
        if (normQuery.contains(normKey) || normKey.contains(normQuery)) {
            if (enHints.any { hint -> lowerOption.contains(hint) }) {
                return true
            }
        }
    }

    return false
}

fun candidateMatchesSearchQuery(
    candidate: com.example.data.model.UserProfile,
    rawQuery: String
): Boolean {
    val trimmed = rawQuery.trim()
    if (trimmed.isEmpty()) return true

    if (candidate.matchesUserIdQuery(trimmed)) return true

    val tokens = trimmed.split(Regex("\\s+")).filter { it.isNotBlank() }
    val searchableFields = listOf(
