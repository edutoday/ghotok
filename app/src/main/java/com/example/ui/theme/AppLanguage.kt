import androidx.compose.runtime.Composable
import androidx.compose.runtime.Immutable
import androidx.compose.runtime.compositionLocalOf

@Immutable
data class LanguageController(
    val isBangla: Boolean = false,
    val onToggleBangla: (Boolean) -> Unit = {}
)

val LocalLanguageController = compositionLocalOf { LanguageController() }

private val BROTHER_REGEX = Regex("""Brother\s*\(s\)""", RegexOption.IGNORE_CASE)
private val SISTER_REGEX = Regex("""Sister\s*\(s\)""", RegexOption.IGNORE_CASE)

@Composable
fun tr(en: String, bn: String): String {
    return if (LocalLanguageController.current.isBangla) bn else en
}

@Composable
fun trNum(value: Any): String {
    val str = value.toString()
    return if (LocalLanguageController.current.isBangla) toBanglaDigits(str) else str
}

fun toBanglaDigits(input: String): String {
    val bnDigits = charArrayOf('০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯')
    val sb = StringBuilder(input.length)
    for (ch in input) {
        if (ch in '0'..'9') {
            sb.append(bnDigits[ch - '0'])
        } else {
            sb.append(ch)
        }
    }
    return sb.toString()
}

@Composable
fun trOption(value: String): String {
    if (!LocalLanguageController.current.isBangla) return value
    return translateValueToBangla(value)
}

fun translateValueToBangla(value: String): String {
    if (value.isBlank()) return value
    exactTranslations[value]?.let { return it }
    val trimmed = value.trim()
    exactTranslations[trimmed]?.let { return it }
    exactTranslationsIgnoreCase[trimmed.lowercase()]?.let { return it }
    com.example.data.model.BangladeshLocationData.getBanglaName(trimmed)?.let { return it }

    if (value.contains("Brother", ignoreCase = true) || value.contains("Sister", ignoreCase = true)) {
        val replaced = value
            .replace(BROTHER_REGEX, "ভাই")
            .replace(SISTER_REGEX, "বোন")
        return toBanglaDigits(replaced)
    }

    // Handle comma-separated lists
    if (value.contains(", ")) {
        return value.split(", ").joinToString(", ") { part ->
            val p = part.trim()
            exactTranslations[p]
                ?: exactTranslationsIgnoreCase[p.lowercase()]
                ?: com.example.data.model.BangladeshLocationData.getBanglaName(p)
                ?: toBanglaDigits(p)
        }
    }

    return toBanglaDigits(value)
}

fun normalizeBanglaSearchText(text: String): String {
    if (text.isEmpty()) return text
    return toBanglaDigits(text)
        .replace("\u09DF", "\u09AF\u09BC") // য় -> য়
        .replace("\u09DC", "\u09A1\u09BC") // ড় -> ড়
        .replace("\u09DD", "\u09A2\u09BC") // ঢ় -> ঢ়
        .replace("ওয়", "ওয়")
        .replace("ী", "ি")
        .replace("ূ", "ু")
        .replace("ণ", "ন")
        .replace("ষ", "শ")
        .replace("স", "শ")
        .replace("ৎ", "ত")
        .replace("ং", "ঙ")
        .trim()
        .lowercase()
}

